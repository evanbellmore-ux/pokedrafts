// Builds the vendored @pokedrafts/showdown-sim package: the pinned Pokémon Showdown simulator (c23d2e94) bundled for
// browsers, module workers, Node and vitest, gated, packed into vendor/ (SPEC §6.1). Run only to refresh the package:
//   npm run prepare:showdown-sim            (lite: base-game learnsets replaced by {}; the gate proves Reg M-C is unchanged)
//   npm run prepare:showdown-sim -- --full  (ships the full data set instead)
// npm install and next build never run it.
import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { access, copyFile, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { pathToFileURL } from "node:url";
import * as esbuild from "esbuild";
import { CACHE, ROOT, SHOWDOWN_SOURCE, ensureSource, run } from "./lib/champions-data/sources.mjs";
import { createPatchPlugin, describePatches } from "./lib/showdown-sim/patches.mjs";
import { runGate } from "./lib/showdown-sim/gate.mjs";
import { FORMAT } from "./lib/showdown-sim/fixtures.mjs";

const FULL = process.argv.includes("--full");
const REV = SHOWDOWN_SOURCE.revision;
const SHORT = REV.slice(0, 8);
const UPSTREAM_VERSION = "0.11.11";
const VERSION = `${UPSTREAM_VERSION}-champions.${SHORT}.1`;
const NAME = "@pokedrafts/showdown-sim";
const ESBUILD_VERSION = "0.28.1";
const posix = (path) => path.split("\\").join("/");
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

if (esbuild.version !== ESBUILD_VERSION) throw new Error(`esbuild ${ESBUILD_VERSION} is required (found ${esbuild.version}).`);

// 1. The pinned, hash-checked source.
const source = await ensureSource(SHOWDOWN_SOURCE);
const upstream = JSON.parse(await readFile(join(source, "package.json"), "utf8"));
if (upstream.version !== UPSTREAM_VERSION) throw new Error(`Unexpected upstream version ${upstream.version}.`);

// 2. ts-chacha20 at the exact version and integrity the pinned package-lock.json records (sim/prng.ts imports it).
const lock = JSON.parse(await readFile(join(source, "package-lock.json"), "utf8"));
const chacha = lock.packages["node_modules/ts-chacha20"];
const chachaTgz = join(CACHE, `ts-chacha20-${chacha.version}.tgz`);
if (!existsSync(chachaTgz)) {
  const probeCopy = join(ROOT, `scripts/.cache/training/design/probe/vendor/ts-chacha20-${chacha.version}.tgz`);
  if (existsSync(probeCopy)) await copyFile(probeCopy, chachaTgz);
  else {
    const response = await fetch(chacha.resolved, { signal: AbortSignal.timeout(60_000) });
    if (!response.ok) throw new Error(`ts-chacha20 download failed: ${response.status}`);
    await writeFile(chachaTgz, Buffer.from(await response.arrayBuffer()));
  }
}
const integrity = "sha512-" + createHash("sha512").update(await readFile(chachaTgz)).digest("base64");
if (integrity !== chacha.integrity) throw new Error("ts-chacha20 integrity does not match the pinned package-lock.json.");
const chachaDir = join(CACHE, `ts-chacha20-${chacha.version}`);
if (!existsSync(join(chachaDir, "package.json"))) {
  await mkdir(chachaDir, { recursive: true });
  run("tar", ["-xzf", posix(relative(chachaDir, chachaTgz)), "--strip-components=1"], chachaDir);
}
const chachaPkg = JSON.parse(await readFile(join(chachaDir, "package.json"), "utf8"));
if (chachaPkg.version !== chacha.version) throw new Error("ts-chacha20 extraction does not match its archive.");

// 3. Generated sources: the static data registry (full and lite), a node:util stand-in, the entry.
const gen = join(CACHE, `showdown-sim-build-${SHORT}`);
await rm(gen, { recursive: true, force: true });
await mkdir(gen, { recursive: true });
const mods = (await readdir(join(source, "data/mods"), { withFileTypes: true })).filter((d) => d.isDirectory()).map((d) => d.name).sort();
const entries = [];
for (const name of (await readdir(join(source, "data"))).sort()) if (name.endsWith(".ts") && !name.endsWith(".d.ts")) entries.push(`data/${name.slice(0, -3)}`);
for (const name of (await readdir(join(source, "data/mods/champions"))).sort()) if (name.endsWith(".ts")) entries.push(`data/mods/champions/${name.slice(0, -3)}`);
entries.push("config/formats");
const stubFile = join(gen, "learnsets-stub.ts");
await writeFile(stubFile, "// Lite data: no base-game learnsets (battles never read them; only TeamValidator does, and Reg M-C reads the champions mod's).\nexport const Learnsets = {};\n");
async function writeRegistry(file, lite) {
  const ids = entries.map((id, i) => ({ id, v: `m${i}`, file: posix(lite && id === "data/learnsets" ? stubFile : join(source, `${id}.ts`)) }));
  await writeFile(file, [
    "// GENERATED by scripts/prepare-showdown-sim.mjs: the data modules the bundled simulator can load (sim/dex.ts loadDataFile).",
    ...ids.map(({ v, file: path }) => `import * as ${v} from ${JSON.stringify(path)};`),
    "const MODULES: Record<string, unknown> = {",
    ...ids.map(({ id, v }) => `  ${JSON.stringify(id)}: ${v},`),
    "};",
    "// DexFormats.load needs every format's mod name (sim/dex-formats.ts:670); only champions' data is bundled.",
    `export const PS_MODS: string[] = ${JSON.stringify(mods)};`,
    "function missing(id: string): never { const error = new Error(\"Cannot find module '\" + id + \"'\") as Error & { code: string }; error.code = \"MODULE_NOT_FOUND\"; throw error; }",
    "export function psRequire(id: string): any { return MODULES[id] ?? missing(id); }",
    "psRequire.resolve = (id: string) => (MODULES[id] ? id : missing(id));",
    "",
  ].join("\n"));
}
const registry = { full: join(gen, "ps-registry.ts"), lite: join(gen, "ps-registry-lite.ts") };
await writeRegistry(registry.full, false);
await writeRegistry(registry.lite, true);
const nodeUtil = join(gen, "node-util.ts");
await writeFile(nodeUtil, [
  "// Stand-in for node:util isDeepStrictEqual (sim/dex-species.ts:3,608): plain objects, arrays, Sets, Maps, primitives.",
  "export function isDeepStrictEqual(a: any, b: any): boolean {",
  "  if (Object.is(a, b)) return true;",
  "  if (typeof a !== 'object' || typeof b !== 'object' || a === null || b === null) return false;",
  "  if (Object.getPrototypeOf(a) !== Object.getPrototypeOf(b)) return false;",
  "  if (a instanceof Set) { if (a.size !== b.size) return false; for (const v of a) if (!b.has(v)) return false; return true; }",
  "  if (a instanceof Map) { if (a.size !== b.size) return false; for (const [k, v] of a) if (!b.has(k) || !isDeepStrictEqual(v, b.get(k))) return false; return true; }",
  "  const ka = Reflect.ownKeys(a), kb = Reflect.ownKeys(b);",
  "  if (ka.length !== kb.length) return false;",
  "  for (const k of ka) { if (!Object.prototype.propertyIsEnumerable.call(b, k)) return false; if (!isDeepStrictEqual(a[k], b[k])) return false; }",
  "  return true;",
  "}",
  "",
].join("\n"));
const entry = join(gen, "entry.ts");
await writeFile(entry, [
  `export { Battle, extractChannelMessages } from ${JSON.stringify(posix(join(source, "sim/battle.ts")))};`,
  `export { Dex, toID } from ${JSON.stringify(posix(join(source, "sim/dex.ts")))};`,
  `export { State } from ${JSON.stringify(posix(join(source, "sim/state.ts")))};`,
  `export { Teams } from ${JSON.stringify(posix(join(source, "sim/teams.ts")))};`,
  `export { TeamValidator } from ${JSON.stringify(posix(join(source, "sim/team-validator.ts")))};`,
  `export { PRNG } from ${JSON.stringify(posix(join(source, "sim/prng.ts")))};`,
  "",
].join("\n"));

// 4. esbuild, the same options for both variants (Showdown's own build is esbuild with useDefineForClassFields false,
//    tools/build-utils.js:45-50, tsconfig.json:20).
const OPTIONS = {
  bundle: true, format: "esm", platform: "browser", target: "es2020", minify: true,
  // sim/state.ts:377-381 writes refs as `[${obj.constructor.name}:id]` and reads them by name: class names must survive.
  keepNames: true,
  legalComments: "eof",
  tsconfigRaw: { compilerOptions: { useDefineForClassFields: false, target: "es2020" } },
  // data/rulesets.ts:488 reads global.Config.
  define: { global: "globalThis" },
};
const applied = {};
async function bundle(lite) {
  const outfile = join(gen, lite ? "showdown-sim.lite.mjs" : "showdown-sim.full.mjs");
  const result = await esbuild.build({
    ...OPTIONS, entryPoints: [entry], outfile, absWorkingDir: ROOT, metafile: true, logLevel: "warning",
    plugins: [createPatchPlugin({ source, registryFile: lite ? registry.lite : registry.full, chachaEntry: join(chachaDir, chachaPkg.main), nodeUtilFile: nodeUtil, applied })],
  });
  const code = await readFile(outfile);
  const text = code.toString("utf8");
  const nodeBuiltins = [...text.matchAll(/require\(["'](?:node:)?(fs|path|util|crypto|child_process|os|net)["']\)/g)].map((m) => m[1]);
  if (nodeBuiltins.length) throw new Error(`Bundle requires Node built-ins: ${nodeBuiltins.join(", ")}`);
  if (/\beval\(|new Function\(/.test(text)) throw new Error("Bundle contains eval or new Function.");
  if (text.includes(posix(ROOT))) throw new Error("Bundle contains a machine path.");
  return { outfile, bytes: code.length, sha256: sha256(code), inputs: Object.keys(result.metafile.inputs).length };
}
const full = await bundle(false);
const lite = await bundle(true);

// 5. Gate both bundles in this process.
const fullSim = await import(pathToFileURL(full.outfile).href);
const liteSim = await import(pathToFileURL(lite.outfile).href);
for (const sim of [fullSim, liteSim]) {
  for (const name of ["Battle", "extractChannelMessages", "Dex", "toID", "State", "Teams", "TeamValidator", "PRNG"]) {
    if (!(name in sim)) throw new Error(`Bundle export missing: ${name}`);
  }
  if (sim.Battle.name !== "Battle") throw new Error("Class names were not kept.");
}
const gate = runGate(fullSim, liteSim);
console.log(`Gate: ${gate.validation.checks} validations (${gate.validation.differ} differ), ${gate.battles.identical}/${gate.battles.battles} battles identical, clones ${gate.battles.clones.same}/${gate.battles.clones.same + gate.battles.clones.differ}, belief rebuild ${gate.belief.identical}/${gate.belief.decisions} (${gate.ms} ms).`);

// 6. Stage the package.
const stage = join(CACHE, `showdown-sim-package-${SHORT}`);
await rm(stage, { recursive: true, force: true });
await mkdir(join(stage, "dist"), { recursive: true });
const shipped = FULL ? full : lite;
await copyFile(shipped.outfile, join(stage, "dist/index.mjs"));
await copyFile(join(ROOT, "scripts/lib/showdown-sim/index.d.ts"), join(stage, "dist/index.d.ts"));
await copyFile(join(source, "LICENSE"), join(stage, "LICENSE"));
await copyFile(join(chachaDir, "LICENSE"), join(stage, "LICENSE.ts-chacha20"));
const provenance = {
  package: NAME,
  version: VERSION,
  upstreamVersion: UPSTREAM_VERSION,
  source: `https://github.com/smogon/pokemon-showdown/tree/${REV}`,
  revision: REV,
  sourceArchiveSha256: SHOWDOWN_SOURCE.sha256,
  format: FORMAT,
  bundler: `esbuild@${esbuild.version}`,
  options: { ...OPTIONS, entry: "sim/battle.ts Battle + extractChannelMessages, sim/dex.ts Dex + toID, sim/state.ts State, sim/teams.ts Teams, sim/team-validator.ts TeamValidator, sim/prng.ts PRNG" },
  dependencies: { "ts-chacha20": { version: chacha.version, resolved: chacha.resolved, integrity: chacha.integrity, license: chacha.license } },
  patches: describePatches(),
  data: FULL
    ? "full: every base data file, data/mods/champions and config/formats; other mods are names only"
    : "lite: data/learnsets.ts replaced by {} (Reg M-C validation and battles proven identical by the gate); every other base data file, data/mods/champions and config/formats; other mods are names only",
  gate: {
    validations: gate.validation.checks, validationSpecies: gate.validation.species, validationDiffer: gate.validation.differ,
    battles: gate.battles.battles, battlesIdentical: gate.battles.identical, cloneReplays: gate.battles.clones.same,
    beliefRebuild: { decisions: gate.belief.decisions, identical: gate.belief.identical, requestsEqual: gate.belief.requestsEqual },
    fixture: "scripts/lib/showdown-sim/fixtures.mjs: seeds [k + 1, 2, 3, 4], k = 0..19; sha256 of the log without |t:| lines, 16 hex digits",
    logHashes: gate.battles.logHashes,
  },
  bundles: { full: { bytes: full.bytes, sha256: full.sha256 }, lite: { bytes: lite.bytes, sha256: lite.sha256 } },
  distSha256: shipped.sha256,
  build: "npm run prepare:showdown-sim",
  notes: "Node module loading only is patched (no battle logic); dex text tables and random-team generators are not bundled.",
};
await writeFile(join(stage, "PROVENANCE.json"), JSON.stringify(provenance, null, 2) + "\n");
await writeFile(join(stage, "package.json"), JSON.stringify({
  name: NAME,
  version: VERSION,
  description: "Pinned Pokémon Showdown simulator (Champions) bundled as one ES module",
  license: "MIT",
  type: "module",
  // No "sideEffects": false: module initialisation registers the data.
  exports: { ".": { types: "./dist/index.d.ts", default: "./dist/index.mjs" } },
  files: ["dist", "LICENSE", "LICENSE.ts-chacha20", "PROVENANCE.json"],
  repository: { type: "git", url: "https://github.com/smogon/pokemon-showdown.git" },
}, null, 2) + "\n");

// 7. Pack into vendor/ with the notices (as scripts/prepare-champions-engine.mjs does for the calc).
const vendor = join(ROOT, "vendor");
await mkdir(vendor, { recursive: true });
const npm = process.env.npm_execpath || join(dirname(process.execPath), "node_modules/npm/bin/npm-cli.js");
await access(npm);
run(process.execPath, [npm, "pack", "--ignore-scripts", "--pack-destination", vendor], stage);
const archive = `pokedrafts-showdown-sim-${VERSION}.tgz`;
const archiveSha256 = sha256(await readFile(join(vendor, archive)));
await writeFile(join(vendor, "showdown-sim.provenance.json"), JSON.stringify({ ...provenance, archive, sha256: archiveSha256 }, null, 2) + "\n");
await copyFile(join(source, "LICENSE"), join(vendor, "showdown-sim.LICENSE"));
await copyFile(join(chachaDir, "LICENSE"), join(vendor, "ts-chacha20.LICENSE"));
console.log(`Prepared ${archive} (${archiveSha256}); dist ${shipped.bytes} bytes, sha256 ${shipped.sha256}.`);
